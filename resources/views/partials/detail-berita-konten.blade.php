    <p>
        Rapat kerja nasional cabang Sukabumi Raya berlangsung di sekretariat DPC dengan dihadiri perwakilan delapan komisariat basis. Forum ini menjadi ruang musyawarah untuk menetapkan program kaderisasi dan arah kajian organisasi.
    </p>
    <p>
        Sejumlah prioritas yang disepakati mencakup penguatan literasi politik kader, pendampingan komisariat baru, serta konsistensi publikasi hasil kajian di kanal organisasi.
    </p>
    <blockquote class="border-l-4 border-brand bg-paper px-5 py-4 text-base font-bold text-ink">
        "Kaderisasi bukan sekadar serangkaian kegiatan, melainkan proses panjang membangun kebiasaan berpikir dan berkumpul."
    </blockquote>
    <h2 class="pt-2 text-xl font-extrabold tracking-tight text-ink">Sepuluh program prioritas</h2>
    <ol class="list-decimal space-y-2 pl-5 text-muted">
        <li>Kajian tematik lintas komisariat.</li>
        <li>Pendampingan kepemimpinan basis.</li>
        <li>Publikasi jurnal kaderisasi.</li>
        <li>Arsip digital dokumentasi kegiatan.</li>
        <li>Ruang diskusi publik terbuka.</li>
    </ol>
    <p>
        Seluruh kegiatan akan dijelaskan lebih lanjut melalui kanal berita dan kalender organisasi.
    </p>
